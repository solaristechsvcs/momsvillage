CREATE TABLE IF NOT EXISTS site_announcement (
 id TINYINT UNSIGNED PRIMARY KEY,
 title VARCHAR(100) NOT NULL DEFAULT '',body VARCHAR(1000) NOT NULL DEFAULT '',
 tone ENUM('info','important','maintenance') NOT NULL DEFAULT 'info',enabled BOOLEAN NOT NULL DEFAULT FALSE,
 revision INT UNSIGNED NOT NULL DEFAULT 1,updated_by INT UNSIGNED NULL,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY(updated_by) REFERENCES users(id)
);
